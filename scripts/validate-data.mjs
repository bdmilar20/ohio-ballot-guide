import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

import { normalizeQuery, ZIP_PATTERN } from "../src/lookup.mjs";

const dataSource = process.argv[2] ?? new URL("../data/elections.json", import.meta.url);
const locationSource = process.argv[3] ?? new URL("../data/locations.json", import.meta.url);
const officeSource = process.argv[4] ?? new URL("../data/offices.json", import.meta.url);
const countyBoardSource = process.argv[5] ?? new URL("../data/county-boards.json", import.meta.url);
const data = JSON.parse(await readFile(dataSource, "utf8"));
const locations = JSON.parse(await readFile(locationSource, "utf8"));
const officeData = JSON.parse(await readFile(officeSource, "utf8"));
const countyBoardData = JSON.parse(await readFile(countyBoardSource, "utf8"));
const datePattern = /^\d{4}-\d{2}-\d{2}$/;
const electionTypes = new Set(["general", "primary", "special", "local"]);
const electionScopes = new Set(["statewide", "county", "municipal"]);
const coverageStatuses = new Set(["partial", "complete"]);
const orderBases = new Set(["population-2010", "land-area-2020", "single-county"]);
// Ohio has had 88 counties since 1851. A generated file that disagrees has lost
// rows or picked up another state.
const OHIO_COUNTY_COUNT = 88;

function assertDate(value, label) {
  assert.match(value, datePattern, `${label} must use YYYY-MM-DD`);
  assert.equal(
    new Date(`${value}T12:00:00Z`).toISOString().slice(0, 10),
    value,
    `${label} must be a real calendar date`,
  );
}

function assertHttpsUrl(value, label) {
  const url = new URL(value);
  assert.equal(url.protocol, "https:", `${label} must use HTTPS`);
}

assertDate(data.meta.last_reviewed, "meta.last_reviewed");
assert.ok(data.elections.length > 0, "at least one election is required");

// data/locations.json is generated by scripts/build-locations.mjs. These checks
// are what stops a bad regeneration from shipping.
assertDate(locations.meta.generated_on, "locations.meta.generated_on");
const sourceIds = new Set();
for (const source of locations.meta.sources) {
  assert.ok(source.id && source.name && source.provides, "each location source needs id, name, provides");
  assertHttpsUrl(source.url, `locations source ${source.id}`);
  sourceIds.add(source.id);
}

const counties = locations.counties;
const countyIds = Object.keys(counties);
assert.equal(countyIds.length, OHIO_COUNTY_COUNT, `expected ${OHIO_COUNTY_COUNT} Ohio counties`);

assertDate(countyBoardData.meta.last_verified, "county boards meta.last_verified");
assertHttpsUrl(countyBoardData.meta.source_url, "county boards meta.source_url");
assert.deepEqual(
  Object.keys(countyBoardData.counties).sort(),
  [...countyIds].sort(),
  "county board directory must cover the same counties as locations",
);
for (const [countyId, url] of Object.entries(countyBoardData.counties)) {
  assertHttpsUrl(url, `${countyId} board URL`);
}

const seenFips = new Set();
for (const [countyId, county] of Object.entries(counties)) {
  assert.ok(county.name, `${countyId} needs a name`);
  assert.match(county.fips, /^39\d{3}$/, `${countyId} needs an Ohio county FIPS code`);
  assert.ok(!seenFips.has(county.fips), `duplicate county FIPS ${county.fips}`);
  seenFips.add(county.fips);
  assert.equal(normalizeQuery(countyId), countyId, `county id ${countyId} must be query-normalized`);
}

function assertCountyList(countyIdList, label) {
  assert.ok(countyIdList.length > 0, `${label} needs at least one county`);
  assert.equal(new Set(countyIdList).size, countyIdList.length, `${label} repeats a county`);
  for (const countyId of countyIdList) {
    assert.ok(counties[countyId], `${label} references unknown county ${countyId}`);
  }
}

for (const [zip, location] of Object.entries(locations.zips)) {
  assert.match(zip, ZIP_PATTERN, `${zip} is not a five-digit ZIP code`);
  assertCountyList(location.county_ids, `ZIP ${zip}`);
  assert.ok(sourceIds.has(location.source), `ZIP ${zip} cites unlisted source ${location.source}`);
  assert.ok(orderBases.has(location.order_basis), `ZIP ${zip} has an invalid order basis`);
  assert.equal(
    location.county_ids.length === 1,
    location.order_basis === "single-county",
    `ZIP ${zip} order basis disagrees with its county count`,
  );
}

for (const [key, place] of Object.entries(locations.places)) {
  assert.equal(normalizeQuery(key), key, `place key ${key} must be query-normalized`);
  assert.doesNotMatch(key, ZIP_PATTERN, `place key ${key} would shadow a ZIP lookup`);
  assert.ok(place.display_name, `place ${key} needs a display name`);
  assertCountyList(place.county_ids, `place ${key}`);
  assert.ok(sourceIds.has(place.source), `place ${key} cites unlisted source ${place.source}`);
}

assert.deepEqual(
  locations.meta.counts,
  {
    counties: countyIds.length,
    zips: Object.keys(locations.zips).length,
    places: Object.keys(locations.places).length,
  },
  "locations.meta.counts does not match the generated file",
);

// data/offices.json describes the office, never a candidate or a position.
assertDate(officeData.meta.last_reviewed, "offices.meta.last_reviewed");
const offices = officeData.offices;
assert.ok(Object.keys(offices).length > 0, "at least one office is required");

for (const [officeId, office] of Object.entries(offices)) {
  assert.ok(office.title, `${officeId} needs a title`);
  assert.ok(office.summary, `${officeId} needs a summary`);
  assert.ok(office.sources.length > 0, `${officeId} needs at least one official source`);
  for (const source of office.sources) {
    assert.ok(source.label, `${officeId} has an unlabeled source`);
    assertHttpsUrl(source.url, `${officeId}.${source.label}`);
  }
  assertDate(office.last_verified, `${officeId}.last_verified`);
}

const electionIds = new Set();
let raceCount = 0;
let issueCount = 0;

for (const election of data.elections) {
  assert.ok(election.id, "each election needs an id");
  assert.ok(!electionIds.has(election.id), `duplicate election id: ${election.id}`);
  electionIds.add(election.id);
  assert.ok(election.name, `${election.id} needs a name`);
  assertDate(election.date, `${election.id}.date`);
  assert.ok(electionTypes.has(election.type), `${election.id} has an invalid type`);
  assert.ok(electionScopes.has(election.scope), `${election.id} has an invalid scope`);
  assert.ok(election.jurisdiction_ids.length > 0, `${election.id} needs a jurisdiction`);
  assertHttpsUrl(election.official_info_url, `${election.id}.official_info_url`);
  assertDate(election.registration_deadline, `${election.id}.registration_deadline`);
  assertDate(election.early_voting_end, `${election.id}.early_voting_end`);
  assert.ok(election.polls.open && election.polls.close, `${election.id} needs poll hours`);
  assert.ok(Array.isArray(election.statewide_races), `${election.id}.statewide_races must be an array`);
  assert.ok(Array.isArray(election.issues), `${election.id}.issues must be an array`);

  const raceIds = new Set();
  const allRaces = [
    ...election.statewide_races,
    ...Object.values(election.counties).flatMap((county) => county.races),
  ];

  for (const race of allRaces) {
    assert.ok(!raceIds.has(race.id), `duplicate race id in ${election.id}: ${race.id}`);
    raceIds.add(race.id);
    assert.ok(race.scope, `${race.id} needs a scope`);
    assert.ok(race.office, `${race.id} needs an office`);
    assert.ok(offices[race.office_id], `${race.id} references unknown office ${race.office_id}`);
    assert.ok(race.candidates.length > 0, `${race.id} needs candidates`);
    for (const candidate of race.candidates) {
      assert.ok(candidate.name && candidate.party, `${race.id} has an incomplete candidate`);
    }
    assertHttpsUrl(race.source_url, `${race.id}.source_url`);
    for (const source of race.supplemental_sources ?? []) {
      assert.ok(source.label, `${race.id} has an unlabeled supplemental source`);
      assertHttpsUrl(source.url, `${race.id}.${source.label}`);
    }
    assertDate(race.last_verified, `${race.id}.last_verified`);
  }

  for (const issue of election.issues) {
    assert.ok(issue.id, `${election.id} has an issue without an id`);
    assert.ok(issue.label && issue.title && issue.summary, `${issue.id} needs display copy`);
    assertHttpsUrl(issue.source_url, `${issue.id}.source_url`);
    assertDate(issue.last_verified, `${issue.id}.last_verified`);
  }

  for (const [countyId, county] of Object.entries(election.counties)) {
    assert.ok(counties[countyId], `${election.id} references unknown county ${countyId}`);
    assert.ok(Array.isArray(county.races), `${countyId}.races must be an array`);
    if (county.races.length > 0) {
      assert.ok(county.coverage, `${countyId} needs coverage metadata`);
      assert.ok(
        coverageStatuses.has(county.coverage.status),
        `${countyId}.coverage has an invalid status`,
      );
      assert.ok(county.coverage.scope, `${countyId}.coverage needs a scope`);
      assert.ok(county.coverage.summary, `${countyId}.coverage needs a summary`);
      assertHttpsUrl(county.coverage.source_url, `${countyId}.coverage.source_url`);
      assertDate(county.coverage.last_verified, `${countyId}.coverage.last_verified`);
    }
  }

  raceCount += allRaces.length;
  issueCount += election.issues.length;
}

console.log(
  `Validated ${data.elections.length} elections, ${raceCount} contests, ${issueCount} issue, and ${Object.keys(offices).length} office descriptions.`,
);
console.log(
  `Validated ${countyIds.length} counties, ${Object.keys(locations.zips).length} ZIP codes, and ${Object.keys(locations.places).length} place names.`,
);
