for (const [countyId, record] of Object.entries(coverage.counties)) {
  assert.ok(record.vendor_slug, `${countyId} coverage needs the vendor slug it was probed at`);
  assertHttpsUrl(record.listing_url, `${countyId} coverage listing_url`);
  if (record.enumerable) {
    // "Enumerable" is a claim that the vendor served a complete precinct list
    // this adapter parsed in full, so the record has to carry every piece of
    // evidence the adapter's own gates require. Checking only some of them
    // leaves a hand-edited true that validates: a record can otherwise say the
    // county is not served, or that the election was never offered, and still
    // pass. The tuple below is assertEnumeration's requirements, not a stricter
    // set. On a real run some of them are redundant -- parsed === listed cannot
    // hold while a row was skipped -- but a hand-edited record is exactly where
    // that stops being true, so each one is asserted and each one has a test
    // that fails when only it is deleted.
    assert.equal(record.response, "served", `${countyId} is marked enumerable but the vendor did not serve it`);
    assert.equal(record.election_offered, true, `${countyId} is marked enumerable but does not offer this election`);
    assert.ok(record.source_updated_at, `${countyId} is marked enumerable without a source update stamp`);
    assert.ok(record.precinct_rows_parsed > 0, `${countyId} is marked enumerable with no precinct rows`);
    assert.equal(
      record.precinct_rows_parsed,
      record.precinct_rows_listed,
      `${countyId} is marked enumerable but parsed fewer rows than the vendor listed`,
    );
    assert.deepEqual(
      record.skipped_row_reasons,
      {},
      `${countyId} is marked enumerable but declined some of the vendor's rows`,
    );
    assert.deepEqual(
      record.unexplained_row_reasons,
      {},
      `${countyId} is marked enumerable but left rows unparsed`,
    );
    assert.equal(record.blocked, undefined, `${countyId} cannot be both enumerable and blocked`);
    assert.ok(!record.transport_error, `${countyId} cannot be enumerable on a request that failed`);
  } else {
    assert.ok(record.blocked, `${countyId} is not enumerable and must say why`);
  }
}

